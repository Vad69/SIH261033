import type { CauseCode, DataSource, Finding, Project, Simulation, WbsNode } from "./types";

function wbs(
  id: string,
  code: string,
  name: string,
  plannedPct: number,
  actualPct: number,
  budgetCr: number,
  spentCr: number,
  owner: string,
  start: string,
  finish: string,
  children?: WbsNode[],
): WbsNode {
  return { id, code, name, plannedPct, actualPct, budgetCr, spentCr, owner, start, finish, children };
}

function exp(month: string, plannedCr: number, actualCr: number, physicalPct: number) {
  return { month, plannedCr, actualCr, physicalPct };
}

function finding(
  id: string,
  step: Finding["step"],
  severity: Finding["severity"],
  title: string,
  detail: string,
  metric?: string,
  cause?: CauseCode,
): Finding {
  return { id, step, severity, title, detail, metric, cause };
}

function sim(
  id: string,
  assumption: string,
  delayDays: number,
  extraCostCr: number,
  revisedCommissioning: string,
  spiIfActed: number,
  recommendation: string,
): Simulation {
  return { id, assumption, delayDays, extraCostCr, revisedCommissioning, spiIfActed, recommendation };
}

